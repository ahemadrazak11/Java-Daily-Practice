package com.java.practice.day32;

public class WraperClass{
    
	public static void main(String[] args) {
		
		System.out.println("Wrapper Classes");
		
		Byte byt = 10;
		
		Short shrt = 20;
		
		Integer intgr = 30;
		
		Long lng = 40L;
		
		Float flt = 50.0f;
		
		Double dbl = 60.00;
		
		Character ch = 'A';
		
		Boolean bln = true;
		
		System.out.println(byt + "\n" + shrt + "\n" + intgr + "\n" + lng + "\n" + flt + "\n" + dbl + "\n" + ch + "\n" + bln);
	}
}
