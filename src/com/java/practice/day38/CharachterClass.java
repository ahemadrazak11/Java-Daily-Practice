package com.java.practice.day38;

public class CharachterClass {

public static void main(String[] args) {
		
		System.out.println("Character Wrapper Class Methods Example,");
		
		Character ch = Character.valueOf('A'); // primitive value assigned to Character Object.
	
		System.out.println(Character.isDigit('1'));
		
		System.out.println(Character.isLetter('S'));
		
		System.out.println(Character.isLetterOrDigit('>'));
		
		System.out.println(Character.isUpperCase('A'));
		
		System.out.println(Character.isLowerCase('c'));
				
		System.out.println(Character.isWhitespace(' '));
		
		System.out.println(Character.toUpperCase('a'));
		
		System.out.println(Character.toLowerCase('F'));
		
		
		
	}

}
